## 1. 목적

본 약관은 LearnWeaver가 제공하는 학습탐험 경로 생성, 콘텐츠 추천, 학습 기록 및 관련 AI 기능의 이용 조건과 운영 기준을 정합니다.

## 2. 서비스의 성격

LearnWeaver는 사용자가 입력한 주제와 목표를 바탕으로 학습탐험 경로를 만들고, 콘텐츠 탐색과 학습 기록을 돕는 AI 기반 학습 지원 서비스입니다.

LearnWeaver가 제공하는 AI 결과는 학습을 돕기 위한 참고 자료이며, 모든 결과가 정확하거나 완전함을 보장하지 않습니다. 사용자는 AI가 생성한 결과를 스스로 확인하고 필요한 경우 수정하여 사용할 수 있습니다.

베타 기간에는 일부 기능, 화면, 과금 정책, AI 제공자 지원 범위가 변경될 수 있습니다.

## 3. 계정 이용

이용자는 본인 소셜 계정을 통해 가입할 수 있으며, 타인의 계정이나 인증 수단을 무단으로 사용할 수 없습니다.

이용자는 자신의 계정으로 발생한 활동에 대해 책임을 지며, 계정이 도용되었거나 비정상 사용이 의심되는 경우 LearnWeaver에 알려야 합니다.

## 4. AI 기능 이용

LearnWeaver는 학습탐험 경로 생성, 목표 정리, 콘텐츠 추천, 학습 보조 기능 등에 AI를 사용할 수 있습니다.

AI 기능은 사용자가 입력한 주제, 목표, 학습 기록, 선택한 콘텐츠 등을 바탕으로 동작할 수 있습니다.

AI가 생성한 학습 경로, 설명, 추천 결과는 참고용이며, 실제 학습 여부와 활용 책임은 이용자에게 있습니다.

## 5. AI 포인트 및 비용

LearnWeaver는 AI 기능 사용을 위해 AI 포인트 제도를 운영할 수 있습니다.

가입 시 지급되는 포인트, 기능별 차감 기준, 추가 포인트 구매 가능 여부는 서비스 화면 또는 별도 안내에 따릅니다.

AI 포인트 정책은 운영 상황에 따라 변경될 수 있으며, 중요한 변경은 서비스 화면 또는 공지로 안내합니다.

## 6. BYOK/API 키 연결

이용자는 자신이 사용하는 외부 AI 제공자의 API 키를 LearnWeaver에 연결하여 AI 기능을 사용할 수 있습니다.

BYOK는 Bring Your Own Key의 약자로, 이용자가 보유한 API 키를 직접 연결하는 방식을 의미합니다.

BYOK를 사용하는 경우 외부 AI 제공자의 과금 정책에 따라 이용자에게 별도 비용이 발생할 수 있습니다. LearnWeaver는 외부 AI 제공자의 요금, 장애, 정책 변경에 대해 책임지지 않습니다.

이용자는 언제든지 등록한 API 키를 변경하거나 삭제할 수 있어야 합니다.

LearnWeaver는 API 키를 민감 정보로 다루며, 평문 노출을 줄이기 위한 암호화 저장, 접근 제한, 로그 마스킹 등 보안 운영 기준을 적용하거나 강화해 나갑니다.

